// Regenerates supabase/seed.sql from src/content/example-recipes.ts.
// Run with: npm run seed:generate
//
// The generated seed inserts the five example recipes as DRAFTS. Re-running the
// seed never overwrites a recipe that already exists with the same slug.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { exampleRecipes } from "../src/content/example-recipes.ts";

function sqlString(value: string | null | undefined): string {
  if (value == null) return "null";
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlJson(value: unknown): string {
  if (value == null) return "null";
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

function sqlInt(value: number | null | undefined): string {
  return value == null ? "null" : String(Math.trunc(value));
}

const rows = exampleRecipes.map((r) => {
  const values = [
    sqlString(r.title),
    sqlString(r.slug),
    sqlString(r.description),
    sqlString(r.introduction),
    `(select id from public.categories where slug = ${sqlString(r.category_slug)})`,
    sqlJson(r.ingredients),
    sqlJson(r.instructions),
    sqlInt(r.prep_time),
    sqlInt(r.cook_time),
    sqlInt(r.servings),
    sqlString(r.yield_description),
    sqlJson(r.nutrition),
    sqlJson(r.tips),
    sqlJson(r.substitutions),
    sqlString(r.storage_instructions),
    sqlJson(r.faq),
    sqlString(r.featured_image),
    sqlString(r.featured_image_alt),
    sqlString(r.pinterest_image),
    sqlString(r.pinterest_image_alt),
    sqlString(r.seo_title),
    sqlString(r.seo_description),
    sqlString(r.focus_keyword),
    r.is_tested ? "true" : "false",
    "'draft'",
  ];
  return `(\n  ${values.join(",\n  ")}\n)`;
});

const sql = `-- GENERATED by scripts/generate-seed.ts from src/content/example-recipes.ts.
-- Do not edit by hand. Run \`npm run seed:generate\` after changing the source.
--
-- Inserts five example recipes as DRAFTS. They are not public and will not
-- appear in the sitemap until an editor reviews, completes and publishes them.

insert into public.recipes (
  title, slug, description, introduction, category_id,
  ingredients, instructions, prep_time, cook_time, servings, yield_description,
  nutrition, tips, substitutions, storage_instructions, faq,
  featured_image, featured_image_alt, pinterest_image, pinterest_image_alt,
  seo_title, seo_description, focus_keyword, is_tested, status
)
values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;

const target = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
writeFileSync(target, sql);
console.log(`Wrote ${exampleRecipes.length} draft recipes to ${target}`);
